import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH}:{})});
const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.TEST_URL||'http://127.0.0.1:8877/explore/');
await page.locator('[data-popup="display"]').click();
await page.locator('[data-display="notes"]').focus();await page.keyboard.press('Enter');
assert.equal(await page.locator('[data-display="notes"]').evaluate(b=>b===document.activeElement),true);
assert.equal(await page.locator('[data-display="notes"]').getAttribute('aria-pressed'),'true');
await page.keyboard.press('Enter');assert.equal(await page.locator('#settings').isVisible(),true);
await page.locator('#close-settings').click();
assert.equal(await page.locator('[data-popup="display"]').getAttribute('aria-expanded'),'false');
await page.locator('[data-string="1"][data-fret="3"]').focus();await page.keyboard.press('Enter');
assert.equal(await page.locator('[data-string="1"][data-fret="3"]').evaluate(b=>b===document.activeElement),true);
assert.match(await page.locator('#selected-note').innerText(),/1 弦 3 品/);
await page.locator('[data-string="1"][data-fret="4"]').click();await page.waitForTimeout(100);
assert.equal(await page.locator('[data-string="1"][data-fret="4"]').getAttribute('aria-pressed'),'true');
await page.locator('#stop').click();assert.equal(await page.locator('.sounding').count(),0);
await page.locator('#manual').click();await page.locator('#close-wiki').click();assert.equal(await page.locator('#knowledge').isVisible(),false);
assert.deepEqual(errors,[]);console.log('PASS: settings preserve focus and pressed state; repeated selection remains active; fret selection retains DOM focus; rapid notes and stop; Wiki close');await browser.close();
